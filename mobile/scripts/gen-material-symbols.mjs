#!/usr/bin/env node
/**
 * Writes src/ui/material-symbols.ts: the code point of every Material Symbol
 * named in src/ui/icons.ts (`md: '…'`), read from the table expo-symbols ships.
 * Android draws icons as glyphs of the preloaded Material Symbols font, so a
 * row never flashes empty while expo-symbols' view loads its font.
 *
 * Usage: npm run icons:gen (CI runs it and fails on a diff, like api:generate)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const symbols = JSON.parse(
  fs.readFileSync(path.join(root, 'node_modules/expo-symbols/build/android/symbols.json'), 'utf8'),
);
const icons = fs.readFileSync(path.join(root, 'src/ui/icons.ts'), 'utf8');
const names = [...new Set([...icons.matchAll(/\bmd: '([a-z0-9_]+)'/g)].map((m) => m[1]))].sort();

const missing = names.filter((n) => !(n in symbols));
if (missing.length) {
  console.error(`unknown Material Symbols: ${missing.join(', ')}`);
  process.exit(1);
}

const body = names.map((n) => `  ${n}: 0x${symbols[n].toString(16)},`).join('\n');
const out = `// Generated by scripts/gen-material-symbols.mjs. Do not edit; run \`npm run icons:gen\`.

/** Code points in the Material Symbols font (expo-symbols/androidWeights/regular). */
export const MATERIAL_SYMBOLS: Record<string, number> = {
${body}
};
`;
fs.writeFileSync(path.join(root, 'src/ui/material-symbols.ts'), out);
console.log(`icons: wrote ${names.length} Material Symbols`);
