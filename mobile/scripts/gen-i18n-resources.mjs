#!/usr/bin/env node
/**
 * Writes src/core/i18n/resources.ts: static imports of every namespace under
 * src/core/i18n/locales, plus catalogs shared with the panel
 * (frontend/src/locales), listed in WEB, so web and mobile say the same thing
 * (API error codes now; status labels and field names as screens arrive).
 *
 * Usage: npm run i18n:gen   (after adding a namespace JSON file)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { LANGUAGES } from './i18n-languages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = path.join(root, 'src/core/i18n/locales');
const out = path.join(root, 'src/core/i18n/resources.ts');
/** Panel catalog file → namespace in the app (the app's own `common` stays separate from the panel's). */
const WEB = {
  errors: 'errors',
  activity: 'activity',
  customers: 'customers',
  agreements: 'agreements',
  vehicles: 'vehicles',
  vehicle_blocks: 'vehicle_blocks',
  vehicle_records: 'vehicle_records',
  rentals: 'rentals',
  inspections: 'inspections_web',
  reservations: 'reservations',
  availability: 'availability',
  payments: 'payments',
  customer_portal: 'customer_portal',
  finance: 'finance',
  deposits: 'deposits',
  transfers: 'transfers',
  fleet_calendar: 'fleet_calendar',
  reports: 'reports',
  invoices: 'invoices',
  suppliers: 'suppliers',
  profitability: 'profitability',
  tenant_settings: 'tenant_settings',
  tenant_members: 'tenant_members',
  tenant_roles: 'tenant_roles',
  invitations: 'invitations',
  support_access: 'support_access',
  permissions: 'permissions',
  notification_engine: 'notification_engine',
  whatsapp: 'whatsapp',
  public_api: 'public_api',
  site_leads: 'site_leads',
  kabis: 'kabis',
  tolls: 'tolls',
  branches: 'branches',
  fleet: 'fleet',
  pricing: 'pricing',
  extras: 'extras',
  campaigns: 'campaigns',
  one_way_rules: 'one_way_rules',
  channels: 'channels',
};
const WEB_NS = Object.values(WEB);

const namespaces = fs
  .readdirSync(path.join(localesDir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort((a, b) => (a === 'common' ? -1 : b === 'common' ? 1 : a.localeCompare(b)));
const clash = namespaces.filter((n) => WEB_NS.includes(n));
if (clash.length) throw new Error(`namespace owned by the panel: ${clash.join(', ')}`);

const id = (lang, ns) => `${lang.replace('-', '')}_${ns}`;
const lines = ['// Generated by scripts/gen-i18n-resources.mjs. Do not edit; run `npm run i18n:gen`.', ''];
for (const lang of LANGUAGES) {
  for (const ns of namespaces) lines.push(`import ${id(lang, ns)} from './locales/${lang}/${ns}.json';`);
  for (const [file, ns] of Object.entries(WEB))
    lines.push(`import ${id(lang, ns)} from '../../../../frontend/src/locales/${lang}/${file}.json';`);
}
const all = [...namespaces, ...WEB_NS];
lines.push(
  '',
  `export const NAMESPACES = [${all.map((n) => `'${n}'`).join(', ')}] as const;`,
  '',
  'export const resources = {',
);
for (const lang of LANGUAGES) lines.push(`  ${lang}: { ${all.map((n) => `${n}: ${id(lang, n)}`).join(', ')} },`);
lines.push('};', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`resources.ts: ${LANGUAGES.length} languages × ${all.length} namespaces`);
