#!/usr/bin/env node
/**
 * Copies the organization-scoped permission slugs (`tenant.*`, plus the
 * account-level `auth.*` and `notifications.*` that stay valid inside an
 * organization) from the panel's catalog `../frontend/src/config/permissions.ts`
 * into `src/core/auth/permission-slugs.ts`, keeping the panel's key names.
 * `src/core/auth/permission-slugs.test.ts` fails when the copy is stale.
 *
 * Usage: npm run permissions:gen
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { readPanelPermissions } from './panel-permissions.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entries = readPanelPermissions(path.join(root, '../frontend/src/config/permissions.ts'));

const body = entries.map(([key, slug]) => `  ${key}: '${slug}',`).join('\n');
const out = `// Generated by scripts/gen-permissions.mjs from frontend/src/config/permissions.ts. Do not edit; run \`npm run permissions:gen\`.

/** Permission slugs the app can check inside an organization (the panel's key names). */
export const Permission = {
${body}
} as const;

export type PermissionSlug = (typeof Permission)[keyof typeof Permission];
`;
fs.writeFileSync(path.join(root, 'src/core/auth/permission-slugs.ts'), out);
console.log(`permission-slugs.ts: ${entries.length} slugs`);
